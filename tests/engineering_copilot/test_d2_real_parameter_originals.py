@pytest.mark.parametrize("profile", PROFILES, ids=[p[3] + "-" + p[9] for p in PROFILES])
def test_real_original_through_explicit_test_only_mapping(tmp_path, profile):
    roots = os.environ.get("EMBRIX_D2_REAL_ORIGINAL_ROOTS")
    if not roots:
        pytest.skip("NOT_RUN: explicit already-acquired original roots required")
    (
        filename,
        digest,
        manufacturer,
        mpn,
        package,
        revision,
        page,
        table,
        row,
        key,
        bound,
        value,
        unit,
        mode,
    ) = profile
    matches = [
        Path(root) / filename
        for root in roots.split(os.pathsep)
        if (Path(root) / filename).is_file()
    ]
    assert len(matches) == 1, "Missing or ambiguous acquired original"
    raw = matches[0].read_bytes()
    assert hashlib.sha256(raw).hexdigest() == digest
    shutil.copyfile(matches[0], tmp_path / filename)
    source_fp = "sha256:" + hashlib.sha256(b"ISOLATED_TEST_IDENTITY_ONLY").hexdigest()
    entry = {
        "kind": "PDF",
        "document_uri": "isolated-test://" + filename,
        "document_revision": revision,
        "relative_path": filename,
        "content_sha256": "sha256:" + digest,
        "source_record_id": "isolated-test-only",
        "source_record_fingerprint": source_fp,
        "manufacturer": manufacturer,
        "mpn": mpn,
        "package": package,
    }
    mapping = {
        "schema_version": 1,
        "tenant_id": "isolated-test",
        "project_id": "isolated-test",
        "documents": [entry],
    }
    (tmp_path / ".embrix").mkdir()
    path = tmp_path / ".embrix" / "parameter-documents.json"

    def save():
        path.write_text(json.dumps(mapping), encoding="utf-8")

    save()
    candidate = ParameterCandidate(
        evidence_id="isolated-test-only",
        tenant_id="isolated-test",
        project_id="isolated-test",
        conversation_id="isolated-test",
        source_record_id=entry["source_record_id"],
        source_record_fingerprint=source_fp,
        manufacturer=manufacturer,
        mpn=mpn,
        package=package,
        document_uri=entry["document_uri"],
        document_revision=revision,
        content_sha256=entry["content_sha256"],
        locator=ParameterLocator(page=page, table=table, row=row),
        parameter_key=key,
        bound_kind=bound,
        value_decimal=value,
        unit=unit,
        conditions=ParameterConditions(mode=mode, package=package),
    )
    port = ProjectMappedParameterPort(lambda tenant, project: tmp_path)
    assert port.read_parameter(candidate) == candidate

    def changed(**updates):
        return ParameterCandidate.model_validate(
            {**candidate.model_dump(mode="python"), **updates, "fingerprint": AUTO}
        )

    with pytest.raises(ValueError):
        port.read_parameter(changed(value_decimal="999"))
    with pytest.raises(ValueError):
        port.read_parameter(
            changed(locator=ParameterLocator(page=page, table=table, row="invalid"))
        )
    with pytest.raises(ValueError):
        port.read_parameter(
            changed(
                conditions=ParameterConditions(
                    mode=mode,
                    package=package,
                    voltage_min="3",
                    voltage_max="3.6",
                    temperature_min="0",
                    temperature_max="70",
                )
            )
        )
    required = ParameterConditions(
        mode="I2C_STANDARD",
        package=package,
        voltage_min="3",
        voltage_max="3.6",
        temperature_min="0",
        temperature_max="70",
    )
    assert not candidate.conditions.covers(required)
    entry["document_revision"] = "incorrect-revision"
    save()
    with pytest.raises(ValueError):
        port.read_parameter(changed(document_revision="incorrect-revision"))
    entry["document_revision"] = revision
    entry["package"] = "WRONG_PACKAGE"
    save()
    with pytest.raises(ValueError):
        port.read_parameter(
            changed(
                package="WRONG_PACKAGE",
                conditions=ParameterConditions(mode=mode, package="WRONG_PACKAGE"),
            )
        )
