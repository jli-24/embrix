from __future__ import annotations

from datetime import datetime
from typing import Protocol, runtime_checkable

from .models import (
    ApprovedContextRecord,
    AuditEvent,
    EngineeringFinding,
    EvidenceRecord,
    FindingDraft,
    OperationProposal,
    ProposalReviewBinding,
    StatusHistory,
    ValidationRequest,
)


@runtime_checkable
class EvidenceSourcePort(Protocol):
    def get_evidence(self, tenant_id: str, project_id: str, evidence_id: str) -> EvidenceRecord | None: ...


@runtime_checkable
class ApprovedContextPort(Protocol):
    def get_memory(self, tenant_id: str, project_id: str, memory_id: str) -> ApprovedContextRecord | None: ...
    def get_knowledge(self, tenant_id: str, project_id: str, knowledge_id: str) -> ApprovedContextRecord | None: ...


@runtime_checkable
class ValidationRulePort(Protocol):
    def evaluate(
        self,
        request: ValidationRequest,
        evidence: tuple[EvidenceRecord, ...],
        memory: tuple[ApprovedContextRecord, ...],
        knowledge: tuple[ApprovedContextRecord, ...],
    ) -> tuple[FindingDraft, ...]: ...


@runtime_checkable
class ClockPort(Protocol):
    def now(self) -> datetime: ...


@runtime_checkable
class ProposalStorePort(Protocol):
    def is_project_tombstoned(self, tenant_id: str, project_id: str) -> bool: ...
    def tombstone_project(self, tenant_id: str, project_id: str, tombstoned_at: str) -> bool: ...
    def save_request(self, request: ValidationRequest) -> ValidationRequest: ...
    def get_request(self, tenant_id: str, project_id: str, validation_id: str) -> ValidationRequest | None: ...
    def list_requests(self, tenant_id: str, project_id: str) -> tuple[ValidationRequest, ...]: ...
    def save_finding(self, finding: EngineeringFinding) -> EngineeringFinding: ...
    def get_finding(self, tenant_id: str, project_id: str, finding_id: str) -> EngineeringFinding | None: ...
    def list_findings(self, tenant_id: str, project_id: str) -> tuple[EngineeringFinding, ...]: ...
    def save_result(self, result: object) -> object: ...
    def get_result(self, tenant_id: str, project_id: str, validation_id: str) -> object | None: ...
    def save_proposal(self, proposal: OperationProposal) -> OperationProposal: ...
    def get_proposal(self, tenant_id: str, project_id: str, proposal_id: str) -> OperationProposal | None: ...
    def list_proposals(self, tenant_id: str, project_id: str) -> tuple[OperationProposal, ...]: ...
    def save_review(self, review: ProposalReviewBinding) -> ProposalReviewBinding: ...
    def get_review(self, tenant_id: str, project_id: str, review_id: str) -> ProposalReviewBinding | None: ...
    def list_reviews(self, tenant_id: str, project_id: str) -> tuple[ProposalReviewBinding, ...]: ...
    def append_history(self, history: StatusHistory) -> StatusHistory: ...
    def append_audit(self, event: AuditEvent) -> AuditEvent: ...


__all__ = (
    "ApprovedContextPort",
    "ClockPort",
    "EvidenceSourcePort",
    "ProposalStorePort",
    "ValidationRulePort",
)
